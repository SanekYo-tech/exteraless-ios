/// The native bubble's action surface. Replies, forwarded sources and special post actions
/// navigate using their ORIGINAL composite IDs; media, reactions, voting, copying and sharing
/// run through native facilities. The feed has no composer or outgoing-message transition.
func exteralessFeedMessageInteraction(owner: ExteralessFeedController, post: ExteralessFeedPost) -> ChatControllerInteraction {
    let id = post.primaryId
    let source: () -> Void = { [weak owner] in owner?.feedOpenSource(id) }
    let openId: (EngineMessage.Id) -> Void = { [weak owner] id in owner?.feedOpenSource(id) }
    let openMessage: (EngineRawMessage) -> Void = { [weak owner] message in owner?.feedOpenSource(message.id) }
    let notice: (String) -> Void = { [weak owner] text in owner?.feedShowNotice(text) }
    let interaction = ChatControllerInteraction(
        openMessage: { [weak owner] message, params in owner?.feedOpenMedia(message, params: params) ?? false },
        openPeer: { [weak owner] peer, _, _, _ in owner?.feedOpenPeer(peer) },
        openPeerMention: { [weak owner] name, _ in owner?.feedOpenURL("https://t.me/\(name)", concealed: false, messageId: id) },
        openMessageContextMenu: { [weak owner] message, _, _, _, _, _ in owner?.feedShowPostMenu(message.id) },
        openMessageReactionContextMenu: { [weak owner] message, _, _, _ in owner?.feedShowPostMenu(message.id) },
        updateMessageReaction: { [weak owner] message, reaction, _, _ in owner?.feedUpdateReaction(message, reaction: reaction) },
        activateMessagePinch: { _ in source() },
        openMessageContextActions: { [weak owner] message, _, _, _ in owner?.feedShowPostMenu(message.id) },
        navigateToMessage: { [weak owner] _, target, params in owner?.feedOpenSource(target, setupReply: params.setupReply, timecode: params.timestamp) },
        navigateToMessageStandalone: openId,
        navigateToThreadMessage: { [weak owner] peer, _, target in
            if let target { owner?.feedOpenSource(target) } else { owner?.feedOpenSource(id, setupReply: true, discussionPeer: peer) }
        },
        tapMessage: nil,
        clickThroughMessage: { _, _ in },
        toggleMessagesSelection: { [weak owner] ids, value in owner?.feedToggleSelection(ids, selected: value) },
        sendCurrentMessage: { _, _ in source() },
        sendMessage: { _, _ in source() },
        sendSticker: { _, _, _, _, _, _, _, _, _ in source(); return false },
        sendEmoji: { _, _, _ in source() },
        sendGif: { _, _, _, _, _ in source(); return false },
        sendBotContextResultAsGif: { _, _, _, _, _, _ in source(); return false },
        editGif: { _, _ in source() },
        requestMessageActionCallback: { message, _, _, _, _ in openMessage(message) },
        requestMessageActionUrlAuth: { _, _ in source() },
        activateSwitchInline: { _, _, _ in source() },
        openUrl: { [weak owner] params in owner?.feedOpenURL(params.url, concealed: params.concealed, messageId: params.message?.id ?? id) },
        openExternalInstantPage: { [weak owner] params in owner?.feedOpenURL(params.url, concealed: params.concealed, messageId: id) },
        shareCurrentLocation: { _ in source() },
        shareAccountContact: { _ in source() },
        sendBotCommand: { _, _ in source() },
        openInstantPage: { message, _ in openMessage(message) },
        openWallpaper: openMessage,
        openTheme: openMessage,
        openHashtag: { _, _ in source() },
        updateInputState: { _ in source() },
        updateInputMode: { _ in source() },
        updatePresentationState: { _ in },
        openMessageShareMenu: { [weak owner] id in owner?.feedShare([id]) },
        presentController: { [weak owner] controller, _ in owner?.feedPresent(controller) },
        presentControllerInCurrent: { [weak owner] controller, _ in owner?.feedPresent(controller) },
        navigationController: { [weak owner] in owner?.feedNavigationController },
        chatControllerNode: { [weak owner] in owner?.displayNode },
        presentGlobalOverlayController: { [weak owner] controller, _ in owner?.feedPresent(controller) },
        callPeer: { _, _ in source() },
        openConferenceCall: openMessage,
        longTap: { [weak owner] _, params in owner?.feedShowPostMenu(params?.message?.id ?? id) },
        todoItemLongTap: { _, _ in source() },
        pollOptionLongTap: { _, _ in source() },
        openCheckoutOrReceipt: { id, _ in openId(id) },
        openSearch: source,
        setupReply: { [weak owner] id in owner?.feedOpenSource(id, setupReply: true) },
        canSetupReply: { _ in .reply },
        canSendMessages: { false },
        navigateToFirstDateMessage: { _, _ in source() },
        requestRedeliveryOfFailedMessages: openId,
        addContact: { _ in source() },
        rateCall: { message, _, _ in openMessage(message) },
        requestSelectMessagePollOptions: { [weak owner] id, options in owner?.feedVote(id, options: options) },
        requestAddMessagePollOption: { id, _, _, _, _ in openId(id) },
        requestOpenMessagePollResults: { id, _ in openId(id) },
        openAppStorePage: source,
        displayMessageTooltip: { _, text, _, _, _ in notice(text) },
        seekToTimecode: { [weak owner] message, timestamp, _ in _ = owner?.feedOpenMedia(message, params: OpenMessageParams(mode: .timecode(timestamp))) },
        scheduleCurrentMessage: { _ in source() },
        sendScheduledMessagesNow: { _ in source() },
        editScheduledMessagesTime: { _ in source() },
        performTextSelectionAction: { [weak owner] message, _, text, entities, action in owner?.feedTextAction(messageId: message?.id ?? id, text: text, entities: entities, action: action) },
        displayImportedMessageTooltip: { _ in source() },
        displaySwipeToReplyHint: { notice("Reply opens this post's channel discussion.") },
        dismissReplyMarkupMessage: { _ in source() },
        openMessagePollResults: { id, _ in openId(id) },
        openPollCreation: { _, _ in source() },
        openPollMedia: { [weak owner] message, subject in owner?.feedOpenPollMedia(message, subject: subject) },
        displayPollSolution: { _, _ in source() },
        displayPsa: { _, _ in source() },
        displayDiceTooltip: { _ in source() },
        animateDiceSuccess: { _, _ in },
        displayPremiumStickerTooltip: { _, message in openMessage(message) },
        displayEmojiPackTooltip: { _, message in openMessage(message) },
        openPeerContextMenu: { [weak owner] peer, _, _, _, _ in owner?.feedShowChannelMenu(peer.id) },
        openMessageReplies: { [weak owner] id, _, _ in owner?.feedOpenSource(id, setupReply: true) },
        openReplyThreadOriginalMessage: openMessage,
        openMessageStats: openId,
        editMessageMedia: { id, _ in openId(id) },
        copyText: { [weak owner] text in owner?.feedCopyText(messageId: id, text: text) },
        displayUndo: { _ in },
        isAnimatingMessage: { _ in false },
        getMessageTransitionNode: { nil },
        updateChoosingSticker: { _ in },
        commitEmojiInteraction: { _, _, _, _ in },
        openLargeEmojiInfo: { _, _, _ in source() },
        openJoinLink: { [weak owner] link in owner?.feedOpenURL(link, concealed: false, messageId: id) },
        openWebView: { _, _, _, _, _ in source() },
        activateAdAction: { _, _, _, _ in },
        adContextAction: { _, _, _ in },
        removeAd: { _ in },
        openRequestedPeerSelection: { id, _, _, _ in openId(id) },
        saveMediaToFiles: { [weak owner] id in owner?.feedShare([id]) },
        openNoAdsDemo: source,
        openAdsInfo: source,
        displayGiveawayParticipationStatus: openId,
        openPremiumStatusInfo: { _, _, _, _ in source() },
        openRecommendedChannelContextMenu: { [weak owner] peer, _, _ in owner?.feedShowChannelMenu(peer.id) },
        openGroupBoostInfo: { _, _ in source() },
        openStickerEditor: source,
        openAgeRestrictedMessageMedia: { message, _ in openMessage(message) },
        playMessageEffect: { _ in },
        editMessageFactCheck: openId,
        sendGift: { _ in source() },
        openUniqueGift: { _ in source() },
        openMessageFeeException: source,
        requestMessageUpdate: { [weak owner] id, _, _ in owner?.feedRelayout(id) },
        cancelInteractiveKeyboardGestures: {},
        dismissTextInput: { [weak owner] in owner?.view.endEditing(true) },
        scrollToMessageId: { index, _ in openId(index.id) },
        scrollToMessageIdWithAnchor: { index, _ in openId(index.id) },
        navigateToStory: { message, _ in openMessage(message) },
        attemptedNavigationToPrivateQuote: { _ in notice("This source is not accessible in the current account.") },
        forceUpdateWarpContents: {},
        playShakeAnimation: {},
        displayQuickShare: { [weak owner] id, _, _ in owner?.feedShare([id]) },
        updateChatLocationThread: { _, _ in source() },
        requestToggleTodoMessageItem: { id, _, _ in openId(id) },
        displayTodoToggleUnavailable: { _ in notice("Open the original post to update this list.") },
        openStarsPurchase: { _ in source() },
        openRankInfo: { _, _, _ in source() },
        openSetPeerAvatar: source,
        displayPollRestrictedToast: { _ in notice("Voting is unavailable for this post.") },
        automaticMediaDownloadSettings: owner.context.sharedContext.currentAutomaticMediaDownloadSettings,
        pollActionState: owner.feedPollActionState,
        stickerSettings: ChatInterfaceStickerSettings(),
        presentationContext: ChatPresentationContext(context: owner.context, backgroundNode: owner.feedWallpaper)
    )
    interaction.chatIsRotated = false
    interaction.canReadHistory = false // Receipts are owned by ExteralessFeedReadState.
    interaction.selectionState = owner.feedSelectedIds.isEmpty ? nil : ChatInterfaceSelectionState(selectedIds: owner.feedSelectedIds)
    return interaction
}
